/** Displays that sit within a line of text, and so count as `inline`. */
const INLINE_LEVEL = new Set(['inline', 'inline-block', 'contents', 'ruby', 'ruby-text']);

export function defaultClassification(tagName: string): 'inline' | 'block' {
	const display = DISPLAY[tagName.toLowerCase()] ?? 'inline';
	return INLINE_LEVEL.has(display) ? 'inline' : 'block';
}
